"""
Wizard forms. The answer form collects no personal data (choice keys only), so it does not
carry the honeypot/consent machinery of the public contact forms. The resume form takes a
64-character token generated by the platform.
"""

from __future__ import annotations

from django import forms
from django.utils.translation import gettext_lazy as _

from orientation import engine
from orientation.constants import RESUME_TOKEN_LENGTH


class AnswerForm(forms.Form):
    question_key = forms.CharField(widget=forms.HiddenInput())

    def __init__(self, question: engine.QuestionSpec, *args, **kwargs):
        super().__init__(*args, **kwargs)
        self.question = question
        self.fields["question_key"].initial = question.key
        if question.type == "multiple":
            self.fields["answer"] = forms.MultipleChoiceField(
                choices=[(c.key, c.label_fr) for c in question.choices],
                required=True,
                error_messages={
                    "required": _("Sélectionnez au moins une réponse."),
                    "invalid_choice": _("Réponse non reconnue."),
                },
            )
        elif question.type == "boolean":
            self.fields["answer"] = forms.ChoiceField(
                choices=[(engine.BOOLEAN_TRUE, _("Oui")), (engine.BOOLEAN_FALSE, _("Non"))],
                required=True,
                error_messages={
                    "required": _("Sélectionnez une réponse."),
                    "invalid_choice": _("Réponse non reconnue."),
                },
            )
        else:
            self.fields["answer"] = forms.ChoiceField(
                choices=[(c.key, c.label_fr) for c in question.choices],
                required=True,
                error_messages={
                    "required": _("Sélectionnez une réponse."),
                    "invalid_choice": _("Réponse non reconnue."),
                },
            )

    def clean_question_key(self) -> str:
        key = self.cleaned_data["question_key"]
        if key != self.question.key:
            raise forms.ValidationError(_("La question a changé : merci de répondre à nouveau."))
        return key

    def clean_answer(self):
        try:
            return engine.normalise_answer(self.question, self.cleaned_data["answer"])
        except engine.InvalidAnswer as exc:
            raise forms.ValidationError(_("Réponse non reconnue.")) from exc


class ResumeForm(forms.Form):
    token = forms.CharField(
        label=_("Code de reprise"),
        max_length=RESUME_TOKEN_LENGTH + 16,
        help_text=_("Le code de 64 caractères affiché à la fin de votre pré-évaluation."),
        widget=forms.TextInput(attrs={"autocomplete": "off", "spellcheck": "false", "inputmode": "text"}),
    )

    def clean_token(self) -> str:
        from orientation.services import normalise_token

        token = normalise_token(self.cleaned_data["token"])
        if len(token) != RESUME_TOKEN_LENGTH:
            raise forms.ValidationError(_("Ce code n’est pas valide."))
        return token
