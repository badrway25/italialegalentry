MARKS_SRC = ROOT / "static" / "icons" / "marks"
MARK_PARTIALS = ROOT / "templates" / "components" / "sezioni" / "marks"
DESIGN = ROOT / "docs" / "design" / "DESIGN_SYSTEM_2026.md"
LIST_START, LIST_END = "<!-- icon-list:start -->", "<!-- icon-list:end -->"

sys.path.insert(0, str(ROOT / "apps"))
from core import icons  # noqa: E402

NS = "{http://www.w3.org/2000/svg}"
SHAPES = {"path", "circle", "rect", "line", "polyline", "polygon", "ellipse"}
GEOMETRY = {
    "path": {"d"},
    "circle": {"cx", "cy", "r"},
    "rect": {"x", "y", "width", "height", "rx", "ry"},
    "line": {"x1", "y1", "x2", "y2"},
    "polyline": {"points"},
    "polygon": {"points"},
    "ellipse": {"cx", "cy", "rx", "ry"},
}
FILL_ATTRS = {"fill", "fill-opacity", "fill-rule", "stroke"}
STROKE_ATTRS = {"stroke-linecap"}
NUMBER = re.compile(r"[-+]?(?:\d*\.\d+|\d+\.?)(?:[eE][-+]?\d+)?")
HEX = re.compile(r"#[0-9a-fA-F]{3,8}\b")

HEADER = """<svg xmlns="http://www.w3.org/2000/svg" aria-hidden="true" focusable="false">
  <!--
    Italy Legal Entry icon sprite, design V5 ({part}). GENERATED by scripts/build_icons.py from static/icons/src:
    never edit it by hand. One concept, one glyph: apps/core/icons.py, the registry every template goes
    through ({% svg_icon %}, the concept and actor_glyph filters). Every stroke is drawn with vector-effect
    non-scaling-stroke, so the stroke-width of the .icon rule (static/css/components.css, section 2) is CSS
    px at every size; currentColor only. Lucide geometry (ISC) under the ILE treatment, and the notices:
    docs/design-v5/ICON_LICENSES.md.
  -->
  <defs>
"""
FOOTER = "  </defs>\n</svg>\n"


class SourceError(ValueError):
    pass


# ---- V5.22: the 48-grid marks -----------------------------------------------------------------------------------
LAYERS = ("tone", "arch", "mark", "route", "sill")
#: the class of each layer in the inline partial (static/css/v5/_sigillo.css)
LAYER_CLASS = {"tone": "sg-t", "arch": "sg-a", "mark": "sg-m", "route": "sg-r", "sill": "sg-s"}
MARK_ATTRS = {"data-layer", "data-group"}
#: the parameters of one segment of each path command; the arc's rotation and flags are never scaled
ARITY = {"m": 2, "l": 2, "t": 2, "h": 1, "v": 1, "c": 6, "s": 4, "q": 4, "a": 7, "z": 0}
TOKEN = re.compile(r"[MmLlHhVvCcSsQqTtAaZz]|[-+]?(?:\d*\.\d+|\d+\.?)(?:[eE][-+]?\d+)?")


def scale_path(d: str, k: float) -> str:
    """Path data scaled by ``k`` about the origin: every coordinate and radius, never an arc's rotation or flags."""
    out: list[str] = []
    command = ""
    values: list[str] = []

    def flush() -> None:
        if not command:
            return
        n = ARITY[command.lower()]
        if n == 0:
            out.append(command)
            return
        if not values or len(values) % n:
            raise SourceError(f"bad path data near {command!r} in {d[:40]!r}")
        parts = []
        for i, raw in enumerate(values):
            j = i % n
            keep = command.lower() == "a" and j in (2, 3, 4)
            parts.append(raw if keep else fmt(float(raw) * k))
        out.append(command + " ".join(parts))

    for token in TOKEN.findall(d):
        if token.isalpha():
            flush()
            command, values = token, []
        else:
            values.append(token)
    flush()
    return "".join(out)


def read_mark(mid: str) -> list[dict]:
    """The shapes of one mark's 48-grid source, in order: {layer, group, tag, attrs}."""
    path = MARKS_SRC / f"{mid}.svg"
    text = path.read_bytes().decode("utf-8")
    if "\r" in text:
        raise SourceError(f"{path.name}: CR bytes (LF only)")
    if HEX.search(text) or "style" in text:
        raise SourceError(f"{path.name}: a literal colour or a style")
    comments = re.findall(r"<!--(.*?)-->", text, re.S)
    if any("--" in c for c in comments) or "ILE drawing" not in " ".join(comments):
        raise SourceError(f"{path.name}: an ILE drawing says so in one comment, without «--»")
    root = ET.fromstring(text)  # noqa: S314 - the repository's own source, see the module header
    if root.tag != f"{NS}svg" or root.get("viewBox") != "0 0 48 48":
        raise SourceError(f"{path.name}: the root must be <svg viewBox=\"0 0 48 48\">")
    shapes = []
    for element in root:
        tag = element.tag[len(NS):] if element.tag.startswith(NS) else element.tag
        if tag not in ("path", "circle"):
            raise SourceError(f"{path.name}: <{tag}> is not allowed in a mark")
        layer = element.get("data-layer", "")
        if layer not in LAYERS:
            raise SourceError(f"{path.name}: a shape without a known data-layer ({layer!r})")
        allowed = GEOMETRY[tag] | MARK_ATTRS | (FILL_ATTRS if layer == "tone" else set())
        unknown = set(element.attrib) - allowed
        if unknown:
            raise SourceError(f"{path.name}: <{tag}> carries {sorted(unknown)}")
        if (layer == "tone") != (element.get("stroke") == "none"):
            raise SourceError(f"{path.name}: only the tone is filled, and the tone is never stroked")
        shapes.append({"layer": layer, "group": element.get("data-group", ""), "tag": tag, "el": element})
    if not any(s["layer"] == "arch" for s in shapes):
        raise SourceError(f"{path.name}: a mark stands on its architecture (an «arch» layer)")
    return shapes


def mark_symbol_markup(mid: str) -> str:
    """The T2 copy: the 48 drawing at half size on the 24 grid — the tone as it is (scaled), the strokes merged."""
    fills: list[str] = []
    strokes: list[str] = []
    for shape in read_mark(mid):
        el = shape["el"]
        if shape["tag"] == "circle":
            cx, cy, r = (_num(el, a) * 0.5 for a in ("cx", "cy", "r"))
            arc = f"a{fmt(r)} {fmt(r)} 0 1 0"
            geometry = f"M{fmt(cx - r)} {fmt(cy)}{arc} {fmt(2 * r)} 0{arc} {fmt(-2 * r)} 0Z"
        else:
            geometry = scale_path(el.get("d", ""), 0.5)
        if shape["layer"] == "tone":
            tone = el.get("fill-opacity", ".14")
            fills.append(f'<path fill="currentColor" fill-opacity="{tone}" stroke="none" d="{geometry}"/>')
        else:
            strokes.append(geometry)
    return "".join(fills) + f'<path vector-effect="non-scaling-stroke" d="{"".join(strokes)}"/>'


def mark_partial(mid: str) -> bytes:
    """The T1 drawing, inline: one shape per stroke with its layer's class and rank, a moving part in its own group."""
    shapes = read_mark(mid)
    ranks: dict[str, int] = {}
    body: list[str] = []
    open_group = ""
    for shape in shapes:
        el, layer, group = shape["el"], shape["layer"], shape["group"]
        if group != open_group:
            if open_group:
                body.append("</g>")
            if group:
                body.append(f'<g class="sg-g sg-g--{group}">')
            open_group = group
        cls = LAYER_CLASS[layer]
        if layer != "tone":
            rank = ranks.get(layer, 0)
            ranks[layer] = rank + 1
            cls += f" {cls}{rank}"
        names = sorted(GEOMETRY[shape["tag"]])
        geometry = " ".join(f'{name}="{el.get(name)}"' for name in names if el.get(name) is not None)
        length = "" if layer == "tone" else ' pathLength="1"'
        body.append(f'<{shape["tag"]} class="{cls}"{length} {geometry}/>')
    if open_group:
        body.append("</g>")
    head = (
        "{% comment %}GENERATED by scripts/build_icons.py from static/icons/marks/" + mid + ".svg "
        "(V5.22 SECTION_SYSTEM_V2 "
        "§4.9): never edit by hand. The T1 drawing of the mark, inline in its arch seat — "
        "components/sezioni/sigillo.html.{% endcomment %}"
    )
    svg = (
        f'<svg class="sigillo__mark" viewBox="0 0 48 48" data-mark="{mid}" focusable="false" aria-hidden="true">'
        + "".join(body)
        + "</svg>"
    )
    return (head + svg + "\n").encode("utf-8")


def build_mark_partials() -> dict[Path, bytes]:
    sources = {p.stem for p in MARKS_SRC.glob("*.svg")}
    if sources != set(icons.MARK):
        raise SourceError(f"marks and registry differ: {sorted(sources ^ set(icons.MARK))}")
    return {MARK_PARTIALS / f"_{mid}.html": mark_partial(mid) for mid in icons.MARK}


def fmt(value: float) -> str:
    text = f"{value:.3f}".rstrip("0").rstrip(".")
    return "0" if text in ("", "-0") else text


def _num(element: ET.Element, name: str, default: float | None = None) -> float:
    raw = element.get(name)
    if raw is None:
        if default is None:
            raise SourceError(f"<{element.tag[len(NS):]}> needs {name}")
        return default
    return float(raw)


def _absolute_start(d: str) -> str:
    """A path's data with an absolute first moveto: a leading «m» would turn relative once merged."""
    d = d.strip()
    if not d.startswith("m"):
        if not d.startswith("M"):
            raise SourceError(f"path data must start with a moveto: {d[:20]!r}")
        return d
    rest = d[1:]
    numbers = list(NUMBER.finditer(rest))
    if len(numbers) < 2:
        raise SourceError(f"bad moveto in {d[:20]!r}")
    end = numbers[1].end()
    head = f"M{numbers[0].group()} {numbers[1].group()}"
    tail = rest[end:]
    if NUMBER.match(tail.lstrip(" ,")):  # implicit relative linetos follow the first pair
        tail = "l" + tail.lstrip(" ,")
    return head + tail


def _points(raw: str) -> list[str]:
    values = NUMBER.findall(raw)
    if len(values) < 4 or len(values) % 2:
        raise SourceError(f"bad points {raw!r}")
    return [f"{values[i]} {values[i + 1]}" for i in range(0, len(values), 2)]


def to_path(element: ET.Element) -> str:
    tag = element.tag[len(NS):]
    if tag == "path":
        return _absolute_start(element.get("d", ""))
    if tag in ("circle", "ellipse"):
        cx, cy = _num(element, "cx"), _num(element, "cy")
        rx = _num(element, "r") if tag == "circle" else _num(element, "rx")
        ry = rx if tag == "circle" else _num(element, "ry")
        r = f"{fmt(rx)} {fmt(ry)}"
        return f"M{fmt(cx - rx)} {fmt(cy)}a{r} 0 1 0 {fmt(2 * rx)} 0a{r} 0 1 0 {fmt(-2 * rx)} 0Z"
    if tag == "rect":
        x, y = _num(element, "x", 0.0), _num(element, "y", 0.0)
        w, h = _num(element, "width"), _num(element, "height")
        rx = _num(element, "rx", _num(element, "ry", 0.0))
        ry = _num(element, "ry", rx)
        rx, ry = min(rx, w / 2), min(ry, h / 2)
        if not rx and not ry:
            return f"M{fmt(x)} {fmt(y)}h{fmt(w)}v{fmt(h)}h{fmt(-w)}Z"
        r = f"{fmt(rx)} {fmt(ry)} 0 0 1"
        return (
            f"M{fmt(x + rx)} {fmt(y)}h{fmt(w - 2 * rx)}a{r} {fmt(rx)} {fmt(ry)}v{fmt(h - 2 * ry)}"
            f"a{r} {fmt(-rx)} {fmt(ry)}h{fmt(-(w - 2 * rx))}a{r} {fmt(-rx)} {fmt(-ry)}v{fmt(-(h - 2 * ry))}"
            f"a{r} {fmt(rx)} {fmt(-ry)}Z"
        )
    if tag == "line":
        return (
            f"M{fmt(_num(element, 'x1'))} {fmt(_num(element, 'y1'))}"
            f"L{fmt(_num(element, 'x2'))} {fmt(_num(element, 'y2'))}"
        )
    if tag in ("polyline", "polygon"):
        pts = _points(element.get("points", ""))
        return "M" + pts[0] + "L" + " ".join(pts[1:]) + ("Z" if tag == "polygon" else "")
    raise SourceError(f"<{tag}> is not a shape")


def _fill_markup(element: ET.Element) -> str:
    tag = element.tag[len(NS):]
    order = ["fill", "fill-opacity", "fill-rule", "stroke", *sorted(GEOMETRY[tag])]
    attrs = " ".join(f'{name}="{element.get(name)}"' for name in order if element.get(name) is not None)
    return f"<{tag} {attrs}/>"


def read_source(sid: str) -> tuple[list[str], str, dict[str, str]]:
    """The filled shapes (markup), the merged stroked path data, the stroked path's extra attributes."""
    path = SRC / f"{sid}.svg"
    text = path.read_bytes().decode("utf-8")
    if "\r" in text:
        raise SourceError(f"{path.name}: CR bytes (LF only)")
    if HEX.search(text) or "style" in text:
        raise SourceError(f"{path.name}: a literal colour or a style")
    comments = re.findall(r"<!--(.*?)-->", text, re.S)
    if any("--" in c for c in comments):
        raise SourceError(f"{path.name}: «--» inside a comment breaks the XML of a sprite")
    origin = " ".join(comments)
    donor = icons.SYMBOLS[sid].donor
    if donor and f'Lucide "{donor}"' not in origin:
        raise SourceError(f"{path.name}: the registry says Lucide {donor!r}, the source does not")
    if not donor and "ILE drawing" not in origin:
        raise SourceError(f"{path.name}: the registry says an ILE drawing, the source does not")
    root = ET.fromstring(text)  # noqa: S314 - the repository's own source, see the module header
    if root.tag != f"{NS}svg" or root.get("viewBox") != "0 0 24 24":
        raise SourceError(f"{path.name}: the root must be <svg viewBox=\"0 0 24 24\">")
    fills: list[str] = []
    strokes: list[str] = []
    extra: dict[str, str] = {}
    for element in root:
        tag = element.tag[len(NS):] if element.tag.startswith(NS) else element.tag
        if tag not in SHAPES:
            raise SourceError(f"{path.name}: <{tag}> is not allowed")
        attrs = set(element.attrib)
        if element.get("stroke") == "none":
            unknown = attrs - GEOMETRY[tag] - FILL_ATTRS
            if unknown or element.get("fill") != "currentColor":
                raise SourceError(f"{path.name}: a filled shape is fill=currentColor with geometry only ({unknown})")
            fills.append(_fill_markup(element))
            continue
        unknown = attrs - GEOMETRY[tag] - STROKE_ATTRS
        if unknown:
            raise SourceError(f"{path.name}: a stroked shape carries {sorted(unknown)}")
        for name in STROKE_ATTRS & attrs:
            if extra.setdefault(name, element.get(name)) != element.get(name):
                raise SourceError(f"{path.name}: two values of {name} in one symbol")
        strokes.append(to_path(element))
    if not fills and not strokes:
        raise SourceError(f"{path.name}: empty")
    return fills, "".join(strokes), extra


def symbol_markup(sid: str) -> str:
    """One symbol's inner markup: the filled shapes as they are, then the merged stroked path."""
    if sid in icons.MARK:
        return mark_symbol_markup(sid)
    fills, stroke, extra = read_source(sid)
    inner = "".join(fills)
    if stroke:
        more = "".join(f' {k}="{v}"' for k, v in sorted(extra.items()))
        inner += f'<path vector-effect="non-scaling-stroke"{more} d="{stroke}"/>'
    return inner


def build_sprites() -> dict[str, bytes]:
    """The two sprites, by the registry's static path (``icons.SPRITE`` and ``icons.SPRITE_DOMAIN``)."""
    sources = {p.stem for p in SRC.glob("*.svg")} | {p.stem for p in MARKS_SRC.glob("*.svg")}
    registry = set(icons.SYMBOLS)
    if sources != registry:
        raise SourceError(
            f"sources and registry differ: no source for {sorted(registry - sources)}, "
            f"not registered {sorted(sources - registry)}"
        )
    if set(icons.LEGACY) & registry:
        raise SourceError(f"an alias may not be a symbol: {sorted(set(icons.LEGACY) & registry)}")
    if set(icons.SPRITE_OF) != registry or set(icons.SPRITE_OF.values()) - set(icons.SPRITES):
        raise SourceError("SPRITE_OF must give every symbol one of icons.SPRITES")
    out: dict[str, bytes] = {}
    for part in icons.SPRITES:
        label = {
            icons.SPRITE: "the chrome",
            icons.SPRITE_DOMAIN: "the domain concepts",
            icons.SPRITE_MARKS: "the V2 sections: the ILE marks' T2 copies and the V5.22 glyphs",
        }[part]
        lines = [HEADER.replace("{part}", label)]
        for sid in icons.SYMBOLS:
            if icons.SPRITE_OF[sid] == part:
                lines.append(f'    <symbol id="icon-{sid}" viewBox="0 0 24 24">{symbol_markup(sid)}</symbol>\n')
        # The V4-only ids (plan §2.3 «aliases for the V4-only ids … until they are swept»): a producer outside
        # the icon family may still emit one, so the sprite of its target draws it as the V5 symbol of its use.
        aliases = [(a, t) for a, t in icons.LEGACY.items() if icons.SPRITE_OF[t] == part]
        if aliases:
            lines.append("    <!-- V4 aliases, until their producers are swept (apps/core/icons.py LEGACY) -->\n")
        for alias, target in aliases:
            lines.append(f'    <symbol id="icon-{alias}" viewBox="0 0 24 24">{symbol_markup(target)}</symbol>\n')
        lines.append(FOOTER)
        data = "".join(lines).encode("utf-8")
        ET.fromstring(data)  # noqa: S314 - strict XML or nothing; the sprite just built, see the module header
        if len(data) > icons.SPRITE_MAX_BYTES:
            raise SourceError(f"{part} is {len(data)} bytes, over the {icons.SPRITE_MAX_BYTES} ceiling")
        if part == icons.SPRITE and len(data) >= icons.CHROME_SPRITE_MAX_BYTES:
            raise SourceError(f"{part} is {len(data)} bytes: the chrome sprite only ratchets down")
        if part == icons.SPRITE_MARKS and len(data) > icons.MARKS_SPRITE_MAX_BYTES:
            raise SourceError(f"{part} is {len(data)} bytes, over the marks sprite's {icons.MARKS_SPRITE_MAX_BYTES}")
        out[part] = data
    return out


def icon_list() -> str:
    """The grouped list of DS 2026 §13 (Italian, like the document), one row per group of the registry."""
    # «N icone.» on its own line: scripts/regen_design_inventory.py (the steward's) reads exactly that.
    total = len(icons.SYMBOLS) + len(icons.LEGACY)
    rows = [
        f"{total} icone.",
        "",
        f"{len(icons.SYMBOLS)} simboli V5 e {len(icons.LEGACY)} alias V4, nell'ordine dello sprite (generato da "
        "`scripts/build_icons.py` dal registro `apps/core/icons.py`), in tre file: `icons.svg` (la cornice), "
        f"`icons-domain.svg` (i concetti di dominio, {len(icons.DOMAIN_SYMBOLS)} simboli) e `icons-marks.svg` (le "
        f"sezioni V2 di V5.22: le copie T2 dei marchi ILE e i glifi vendorizzati, {len(icons.MARKS_SYMBOLS)} simboli).",
        "",
        "| Gruppo | Icone |",
        "|---|---|",
    ]
    for label, names in icons.GROUPS:
        rows.append(f"| {label} | " + ", ".join(f"`{n}`" for n in names) + " |")
    if icons.LEGACY:
        rows.append(
            "| Alias V4 — fino allo sweep dei loro produttori: ciascuno disegna il simbolo V5 del suo uso residuo "
            "(`apps/core/icons.py`, `LEGACY`) | " + ", ".join(f"`{n}`" for n in icons.LEGACY) + " |"
        )
    return "\n".join(rows)


def with_list(design: str) -> str:
    start, end = design.index(LIST_START) + len(LIST_START), design.index(LIST_END)
    return design[:start] + "\n" + icon_list() + "\n" + design[end:]


def main(argv: list[str] | None = None) -> int:
    parser = argparse.ArgumentParser(description=__doc__.split("\n\n")[0])
    parser.add_argument("--check", action="store_true", help="exit 1 if the sprite or the DS list is not current")
    args = parser.parse_args(argv)
    try:
        sprites = build_sprites()
        partials = build_mark_partials()
    except SourceError as error:
        print(f"build_icons: {error}", file=sys.stderr)
        return 2
    design_bytes = DESIGN.read_bytes()
    design = with_list(design_bytes.decode("utf-8")).encode("utf-8")
    targets = {icons.SPRITE: SPRITE, icons.SPRITE_DOMAIN: SPRITE_DOMAIN, icons.SPRITE_MARKS: SPRITE_MARKS}
    if args.check:
        built = (*((targets[part], data) for part, data in sprites.items()), (DESIGN, design), *partials.items())
        stale = [
            path.relative_to(ROOT).as_posix() for path, new in built if not path.exists() or path.read_bytes() != new
        ]
        orphans = sorted(set(MARK_PARTIALS.glob("_*.html")) - set(partials)) if MARK_PARTIALS.exists() else []
        stale += [path.relative_to(ROOT).as_posix() for path in orphans]
        if stale:
            print(f"build_icons: not current — {', '.join(stale)}; run python scripts/build_icons.py", file=sys.stderr)
            return 1
        sizes = ", ".join(f"{part} {len(data)} B" for part, data in sprites.items())
        print(f"build_icons: current ({len(icons.SYMBOLS)} symbols; {sizes})")
        return 0
    for part, data in sprites.items():
        targets[part].write_bytes(data)
    MARK_PARTIALS.mkdir(parents=True, exist_ok=True)
    for orphan in set(MARK_PARTIALS.glob("_*.html")) - set(partials):
        orphan.unlink()
    for path, data in partials.items():
        path.write_bytes(data)
    if design != design_bytes:
        DESIGN.write_bytes(design)
    for part, data in sprites.items():
        print(f"build_icons: {len(data)} bytes -> {targets[part].relative_to(ROOT).as_posix()}")
    print(f"build_icons: {len(icons.SYMBOLS)} symbols; {len(partials)} inline marks -> "
          f"{MARK_PARTIALS.relative_to(ROOT).as_posix()}")
    return 0


if __name__ == "__main__":
    sys.exit(main())
