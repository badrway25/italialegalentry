"""
Build the ILE icon sprite — design V5, V5.4 plan §1.7 and §2.4 (stdlib only).

    python scripts/build_icons.py          — writes static/img/icons.svg and the icon list of DS 2026 §13
    python scripts/build_icons.py --check  — exits 1 if either is not what the sources give (the currency test)

The sources are ``static/icons/src/<id>.svg``, one drawing per file on the 24 grid; ``apps/core/icons.py`` is
the registry that names them. The build:

* refuses a source that is not strict XML, has another viewBox, carries a colour, a ``style``, a ``<style>`` or a
  ``--`` inside a comment, or an element or attribute outside the short list below; refuses a symbol the registry
  lacks and a registered symbol without a source; refuses a donor comment that disagrees with the registry;
* keeps the filled shapes (``stroke="none"``: the 12 % tone, the filled marks) as they are;
* merges every stroked shape of a symbol — path, circle, rect, line, polyline, polygon, ellipse — into ONE path
  drawn with ``vector-effect="non-scaling-stroke"``: the stroke-width of the ``.icon`` rule is then CSS px at
  every size, so a glyph is 1.5 px at 14 px as at 24 px whatever component sizes it (plan §1.7, «effective
  stroke»). One attribute per symbol keeps the sprite under its ceiling;
* drops the sources' root attributes (they only let a source be looked at on its own) and writes LF bytes;
* writes the grouped list of DS 2026 §13 between ``<!-- icon-list:start -->`` and ``<!-- icon-list:end -->``.

S314: the XML parsed here is the repository's own drawings (``static/icons/src``) and the sprite this script has
just assembled from them, read from the local disk — never network input. defusedxml is not a dependency of this
project and the build adds none (stdlib only).
"""

from __future__ import annotations

import argparse
import re
import sys
import xml.etree.ElementTree as ET
from pathlib import Path

ROOT = Path(__file__).resolve().parents[1]
SRC = ROOT / "static" / "icons" / "src"
SPRITE = ROOT / "static" / "img" / "icons.svg"
DESIGN = ROOT / "docs" / "design" / "DESIGN_SYSTEM_2026.md"
LIST_START, LIST_END = "<!-- icon-list:start -->", "<!-- icon-list:end -->"

sys.path.insert(0, str(ROOT / "apps"))
from core import icons  # noqa: E402

NS = "{http://www.w3.org/2000/svg}"
SHAPES = {"path", "circle", "rect", "line", "polyline", "polygon", "ellipse"}
GEOMETRY = {
    "path": {"d"},
    "circle": {"cx", "cy", "r"},
    "rect": {"x", "y", "width", "height", "rx", "ry"},
    "line": {"x1", "y1", "x2", "y2"},
    "polyline": {"points"},
    "polygon": {"points"},
    "ellipse": {"cx", "cy", "rx", "ry"},
}
FILL_ATTRS = {"fill", "fill-opacity", "fill-rule", "stroke"}
STROKE_ATTRS = {"stroke-linecap"}
NUMBER = re.compile(r"[-+]?(?:\d*\.\d+|\d+\.?)(?:[eE][-+]?\d+)?")
HEX = re.compile(r"#[0-9a-fA-F]{3,8}\b")

HEADER = """<svg xmlns="http://www.w3.org/2000/svg" aria-hidden="true" focusable="false">
  <!--
    Italy Legal Entry icon sprite, design V5. GENERATED by scripts/build_icons.py from static/icons/src:
    never edit it by hand. One concept, one glyph: apps/core/icons.py, the registry every template goes
    through ({% svg_icon %}, the concept and actor_glyph filters). Every stroke is drawn with vector-effect
    non-scaling-stroke, so the stroke-width of the .icon rule (static/css/components.css, section 2) is CSS
    px at every size; currentColor only. Lucide geometry (ISC) under the ILE treatment, and the notices:
    docs/design-v5/ICON_LICENSES.md.
  -->
  <defs>
"""
FOOTER = "  </defs>\n</svg>\n"


class SourceError(ValueError):
    pass


def fmt(value: float) -> str:
    text = f"{value:.3f}".rstrip("0").rstrip(".")
    return "0" if text in ("", "-0") else text


def _num(element: ET.Element, name: str, default: float | None = None) -> float:
    raw = element.get(name)
    if raw is None:
        if default is None:
            raise SourceError(f"<{element.tag[len(NS):]}> needs {name}")
        return default
    return float(raw)


def _absolute_start(d: str) -> str:
    """A path's data with an absolute first moveto: a leading «m» would turn relative once merged."""
    d = d.strip()
    if not d.startswith("m"):
        if not d.startswith("M"):
            raise SourceError(f"path data must start with a moveto: {d[:20]!r}")
        return d
    rest = d[1:]
    numbers = list(NUMBER.finditer(rest))
    if len(numbers) < 2:
        raise SourceError(f"bad moveto in {d[:20]!r}")
    end = numbers[1].end()
    head = f"M{numbers[0].group()} {numbers[1].group()}"
    tail = rest[end:]
    if NUMBER.match(tail.lstrip(" ,")):  # implicit relative linetos follow the first pair
        tail = "l" + tail.lstrip(" ,")
    return head + tail


def _points(raw: str) -> list[str]:
    values = NUMBER.findall(raw)
    if len(values) < 4 or len(values) % 2:
        raise SourceError(f"bad points {raw!r}")
    return [f"{values[i]} {values[i + 1]}" for i in range(0, len(values), 2)]


def to_path(element: ET.Element) -> str:
    tag = element.tag[len(NS):]
    if tag == "path":
        return _absolute_start(element.get("d", ""))
    if tag in ("circle", "ellipse"):
        cx, cy = _num(element, "cx"), _num(element, "cy")
        rx = _num(element, "r") if tag == "circle" else _num(element, "rx")
        ry = rx if tag == "circle" else _num(element, "ry")
        r = f"{fmt(rx)} {fmt(ry)}"
        return f"M{fmt(cx - rx)} {fmt(cy)}a{r} 0 1 0 {fmt(2 * rx)} 0a{r} 0 1 0 {fmt(-2 * rx)} 0Z"
    if tag == "rect":
        x, y = _num(element, "x", 0.0), _num(element, "y", 0.0)
        w, h = _num(element, "width"), _num(element, "height")
        rx = _num(element, "rx", _num(element, "ry", 0.0))
        ry = _num(element, "ry", rx)
        rx, ry = min(rx, w / 2), min(ry, h / 2)
        if not rx and not ry:
            return f"M{fmt(x)} {fmt(y)}h{fmt(w)}v{fmt(h)}h{fmt(-w)}Z"
        r = f"{fmt(rx)} {fmt(ry)} 0 0 1"
        return (
            f"M{fmt(x + rx)} {fmt(y)}h{fmt(w - 2 * rx)}a{r} {fmt(rx)} {fmt(ry)}v{fmt(h - 2 * ry)}"
            f"a{r} {fmt(-rx)} {fmt(ry)}h{fmt(-(w - 2 * rx))}a{r} {fmt(-rx)} {fmt(-ry)}v{fmt(-(h - 2 * ry))}"
            f"a{r} {fmt(rx)} {fmt(-ry)}Z"
        )
    if tag == "line":
        return (
            f"M{fmt(_num(element, 'x1'))} {fmt(_num(element, 'y1'))}"
            f"L{fmt(_num(element, 'x2'))} {fmt(_num(element, 'y2'))}"
        )
    if tag in ("polyline", "polygon"):
        pts = _points(element.get("points", ""))
        return "M" + pts[0] + "L" + " ".join(pts[1:]) + ("Z" if tag == "polygon" else "")
    raise SourceError(f"<{tag}> is not a shape")


def _fill_markup(element: ET.Element) -> str:
    tag = element.tag[len(NS):]
    order = ["fill", "fill-opacity", "fill-rule", "stroke", *sorted(GEOMETRY[tag])]
    attrs = " ".join(f'{name}="{element.get(name)}"' for name in order if element.get(name) is not None)
    return f"<{tag} {attrs}/>"


def read_source(sid: str) -> tuple[list[str], str, dict[str, str]]:
    """The filled shapes (markup), the merged stroked path data, the stroked path's extra attributes."""
    path = SRC / f"{sid}.svg"
    text = path.read_bytes().decode("utf-8")
    if "\r" in text:
        raise SourceError(f"{path.name}: CR bytes (LF only)")
    if HEX.search(text) or "style" in text:
        raise SourceError(f"{path.name}: a literal colour or a style")
    comments = re.findall(r"<!--(.*?)-->", text, re.S)
    if any("--" in c for c in comments):
        raise SourceError(f"{path.name}: «--» inside a comment breaks the XML of a sprite")
    origin = " ".join(comments)
    donor = icons.SYMBOLS[sid].donor
    if donor and f'Lucide "{donor}"' not in origin:
        raise SourceError(f"{path.name}: the registry says Lucide {donor!r}, the source does not")
    if not donor and "ILE drawing" not in origin:
        raise SourceError(f"{path.name}: the registry says an ILE drawing, the source does not")
    root = ET.fromstring(text)  # noqa: S314 - the repository's own source, see the module header
    if root.tag != f"{NS}svg" or root.get("viewBox") != "0 0 24 24":
        raise SourceError(f"{path.name}: the root must be <svg viewBox=\"0 0 24 24\">")
    fills: list[str] = []
    strokes: list[str] = []
    extra: dict[str, str] = {}
    for element in root:
        tag = element.tag[len(NS):] if element.tag.startswith(NS) else element.tag
        if tag not in SHAPES:
            raise SourceError(f"{path.name}: <{tag}> is not allowed")
        attrs = set(element.attrib)
        if element.get("stroke") == "none":
            unknown = attrs - GEOMETRY[tag] - FILL_ATTRS
            if unknown or element.get("fill") != "currentColor":
                raise SourceError(f"{path.name}: a filled shape is fill=currentColor with geometry only ({unknown})")
            fills.append(_fill_markup(element))
            continue
        unknown = attrs - GEOMETRY[tag] - STROKE_ATTRS
        if unknown:
            raise SourceError(f"{path.name}: a stroked shape carries {sorted(unknown)}")
        for name in STROKE_ATTRS & attrs:
            if extra.setdefault(name, element.get(name)) != element.get(name):
                raise SourceError(f"{path.name}: two values of {name} in one symbol")
        strokes.append(to_path(element))
    if not fills and not strokes:
        raise SourceError(f"{path.name}: empty")
    return fills, "".join(strokes), extra


def symbol_markup(sid: str) -> str:
    """One symbol's inner markup: the filled shapes as they are, then the merged stroked path."""
    fills, stroke, extra = read_source(sid)
    inner = "".join(fills)
    if stroke:
        more = "".join(f' {k}="{v}"' for k, v in sorted(extra.items()))
        inner += f'<path vector-effect="non-scaling-stroke"{more} d="{stroke}"/>'
    return inner


def build_sprite() -> bytes:
    sources = {p.stem for p in SRC.glob("*.svg")}
    registry = set(icons.SYMBOLS)
    if sources != registry:
        raise SourceError(
            f"sources and registry differ: no source for {sorted(registry - sources)}, "
            f"not registered {sorted(sources - registry)}"
        )
    if set(icons.LEGACY) & registry:
        raise SourceError(f"an alias may not be a symbol: {sorted(set(icons.LEGACY) & registry)}")
    lines = [HEADER]
    for sid in icons.SYMBOLS:
        lines.append(f'    <symbol id="icon-{sid}" viewBox="0 0 24 24">{symbol_markup(sid)}</symbol>\n')
    # The V4-only ids (plan §2.3 «aliases for the V4-only ids … until they are swept»): a producer outside
    # the icon family may still emit one, so the sprite draws it as the V5 symbol of its remaining use.
    if icons.LEGACY:
        lines.append("    <!-- V4 aliases, until their producers are swept (apps/core/icons.py LEGACY) -->\n")
    for alias, target in icons.LEGACY.items():
        lines.append(f'    <symbol id="icon-{alias}" viewBox="0 0 24 24">{symbol_markup(target)}</symbol>\n')
    lines.append(FOOTER)
    data = "".join(lines).encode("utf-8")
    ET.fromstring(data)  # noqa: S314 - strict XML or nothing; the sprite just built, see the module header
    if len(data) > icons.SPRITE_MAX_BYTES:
        raise SourceError(f"the sprite is {len(data)} bytes, over the {icons.SPRITE_MAX_BYTES} ceiling")
    return data


def icon_list() -> str:
    """The grouped list of DS 2026 §13 (Italian, like the document), one row per group of the registry."""
    # «N icone.» on its own line: scripts/regen_design_inventory.py (the steward's) reads exactly that.
    total = len(icons.SYMBOLS) + len(icons.LEGACY)
    rows = [
        f"{total} icone.",
        "",
        f"{len(icons.SYMBOLS)} simboli V5 e {len(icons.LEGACY)} alias V4, nell'ordine dello sprite (generato da "
        "`scripts/build_icons.py` dal registro `apps/core/icons.py`).",
        "",
        "| Gruppo | Icone |",
        "|---|---|",
    ]
    for label, names in icons.GROUPS:
        rows.append(f"| {label} | " + ", ".join(f"`{n}`" for n in names) + " |")
    if icons.LEGACY:
        rows.append(
            "| Alias V4 — fino allo sweep dei loro produttori: ciascuno disegna il simbolo V5 del suo uso residuo "
            "(`apps/core/icons.py`, `LEGACY`) | " + ", ".join(f"`{n}`" for n in icons.LEGACY) + " |"
        )
    return "\n".join(rows)


def with_list(design: str) -> str:
    start, end = design.index(LIST_START) + len(LIST_START), design.index(LIST_END)
    return design[:start] + "\n" + icon_list() + "\n" + design[end:]


def main(argv: list[str] | None = None) -> int:
    parser = argparse.ArgumentParser(description=__doc__.split("\n\n")[0])
    parser.add_argument("--check", action="store_true", help="exit 1 if the sprite or the DS list is not current")
    args = parser.parse_args(argv)
    try:
        sprite = build_sprite()
    except SourceError as error:
        print(f"build_icons: {error}", file=sys.stderr)
        return 2
    design_bytes = DESIGN.read_bytes()
    design = with_list(design_bytes.decode("utf-8")).encode("utf-8")
    if args.check:
        built = ((SPRITE, sprite), (DESIGN, design))
        stale = [path.relative_to(ROOT).as_posix() for path, new in built if path.read_bytes() != new]
        if stale:
            print(f"build_icons: not current — {', '.join(stale)}; run python scripts/build_icons.py", file=sys.stderr)
            return 1
        print(f"build_icons: current ({len(icons.SYMBOLS)} symbols, {len(sprite)} bytes)")
        return 0
    SPRITE.write_bytes(sprite)
    if design != design_bytes:
        DESIGN.write_bytes(design)
    print(f"build_icons: {len(icons.SYMBOLS)} symbols, {len(sprite)} bytes -> {SPRITE.relative_to(ROOT).as_posix()}")
    return 0


if __name__ == "__main__":
    sys.exit(main())
