"""
Build the ILE icon sprite — design V5, V5.4 plan §1.7 and §2.4 (stdlib only).

    python scripts/build_icons.py          — writes static/img/icons.svg, static/img/icons-domain.svg and the icon
                                             list of DS 2026 §13
    python scripts/build_icons.py --check  — exits 1 if either is not what the sources give (the currency test)

The sources are ``static/icons/src/<id>.svg``, one drawing per file on the 24 grid; ``apps/core/icons.py`` is
the registry that names them. The build:

* refuses a source that is not strict XML, has another viewBox, carries a colour, a ``style``, a ``<style>`` or a
  ``--`` inside a comment, or an element or attribute outside the short list below; refuses a symbol the registry
  lacks and a registered symbol without a source; refuses a donor comment that disagrees with the registry;
* keeps the filled shapes (``stroke="none"``: the 12 % tone, the filled marks) as they are;
* merges every stroked shape of a symbol — path, circle, rect, line, polyline, polygon, ellipse — into ONE path
  drawn with ``vector-effect="non-scaling-stroke"``: the stroke-width of the ``.icon`` rule is then CSS px at
  every size, so a glyph is 1.5 px at 14 px as at 24 px whatever component sizes it (plan §1.7, «effective
  stroke»). One attribute per symbol keeps the sprite under its ceiling;
* drops the sources' root attributes (they only let a source be looked at on its own) and writes LF bytes;
* splits the symbols between two sprites (V5.12 W2, DECISIONS §4): ``icons.svg``, the chrome every page draws, and
  ``icons-domain.svg``, the domain concepts — by the registry's ``SPRITE_OF``, which the ``svg_icon`` tag reads to
  write each ``<use>`` against its own file; a V4 alias lives in its target's sprite. Each sprite stays under
  ``SPRITE_MAX_BYTES``; the chrome sprite also under ``CHROME_SPRITE_MAX_BYTES`` (it only ratchets down);
* writes the grouped list of DS 2026 §13 between ``<!-- icon-list:start -->`` and ``<!-- icon-list:end -->``;
* V5.22 (SECTION_SYSTEM_V2 §4.9, lane S): the thirteen ILE marks are drawn ONCE, on the 48-unit grid, in
  ``static/icons/marks/<id>.svg`` — each shape names its layer (``data-layer``: ``arch``, ``mark``, ``route``, ``tone``,
  ``sill``) and, for a part that moves, its group (``data-group``). From that one source the build writes their T2
  copy into the third sprite, ``icons-marks.svg`` (the drawing at half size on the 24 grid, every stroke merged into
  one non-scaling path, like any symbol; the sprite also holds the Lucide glyphs V5.22 vendored, under
  ``MARKS_SPRITE_MAX_BYTES``), and their T1 drawing as an inline partial,
  ``templates/components/sezioni/marks/_<id>.html``: one shape per stroke, each ``pathLength="1"`` with its layer's
  class and its rank in the layer (``sg-a0``, ``sg-m1`` …) so that ``static/css/v5/_sigillo.css`` draws the arch, then
  the mark, then the route, and fades the tone in last; a moving part in its own ``<g>``.

S314: the XML parsed here is the repository's own drawings (``static/icons/src``) and the sprite this script has
just assembled from them, read from the local disk — never network input. defusedxml is not a dependency of this
project and the build adds none (stdlib only).
"""

