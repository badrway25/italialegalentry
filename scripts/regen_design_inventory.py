"""
Regenerate the inventory tables of DESIGN_SYSTEM_2026.md and the counts of ACCESSIBILITY.md (V5.4 plan §2.2,
merge step 3; §2.4).

    python scripts/regen_design_inventory.py            # check: say what is stale; change nothing
    python scripts/regen_design_inventory.py --write    # rewrite what can be computed

Families never edit these figures by hand (plan §2.2): after each merge the steward runs this script, and the
figures follow the tree. What it REGENERATES — values computed from files, the same way
tests/frontend/test_design_docs.py computes them:

- DS 2026 §2: the weight of every sheet main.css imports (KB, one decimal), the rows in main.css's order and
  numbered 1…n, the row of a sheet main.css no longer imports removed; the «N sezioni numerate» of
  components.css;
- §6.2: «N file woff2» and «≈ N KB in totale» in the heading, each font row's KB, the row of a font no longer on
  disk removed;
- §10: the «N file.» count of templates/components/;
- §13: the «N icone.» count of the sprite; the «N icone disposte … sulle N catture» figures of the capture
  report;
- §16: «≈ N KB non compressi in totale» of static/js/*.js;
- §19: the «**N catture» of the capture report;
- ACCESSIBILITY.md: the «Riepilogo: …» line under the WCAG checklist, recounted from the table; the gap range
  «G-01 … G-nn», in both documents.

What it does NOT write, and says so as «needs a writer» (exit 2): prose. A sheet main.css imports with no row in
§2, a font with no row in §6.2, a component with no section in §10, a sprite id missing from §13's grouped list,
a keyframe of the cascade §12 does not name, a static/js file or an init function §16 does not list — each needs
a sentence a person (the owning family) writes. §12 is CHECKED only: its inventory is prose. The capture report
itself is regenerated by docs/qa/design/capture.py, not here; this script only reads it.

Exit status: 0 — nothing stale (or, with --write, everything rewritten) and nothing needs a writer; 1 — check
mode found stale figures (run --write); 2 — something needs a writer, or a section this script reads is gone.
Files are read and written as UTF-8 bytes with LF line endings.
"""

from __future__ import annotations

import argparse
import json
import re
import sys
from dataclasses import dataclass, field
from pathlib import Path

ROOT = Path(__file__).resolve().parent.parent
DESIGN_DOC = ROOT / "docs" / "design" / "DESIGN_SYSTEM_2026.md"
A11Y_DOC = ROOT / "docs" / "ACCESSIBILITY.md"
STATIC = ROOT / "static"
COMPONENTS = ROOT / "templates" / "components"
CAPTURE_REPORT = ROOT / "docs" / "qa" / "design" / "capture-report.json"

CHECKLIST_STATUSES = ("Conforme", "Da confermare in QA", "Parziale", "Non applicabile")


class Missing(Exception):
    """A heading or a marker this script reads is not in the document any more."""


@dataclass
class Result:
    changes: list[str] = field(default_factory=list)  # what was (or would be) rewritten
    manual: list[str] = field(default_factory=list)  # what needs a writer


def _read(path: Path) -> str:
    return path.read_bytes().decode("utf-8")


def _kb(size: int) -> str:
    return f"{size / 1024:.1f}"


def _span(text: str, start: str, end: str) -> tuple[int, int]:
    """The [begin, end) of the text between two markers (the first ``start``, the first ``end`` after it)."""
    begin = text.find(start)
    if begin < 0:
        raise Missing(start)
    begin += len(start)
    finish = text.find(end, begin)
    if finish < 0:
        raise Missing(end)
    return begin, finish


def _replace_in(text: str, start: str, end: str, edit) -> str:
    begin, finish = _span(text, start, end)
    return text[:begin] + edit(text[begin:finish]) + text[finish:]


def cascade() -> list[str]:
    """The sheets main.css imports, in order (test_design_docs._cascade)."""
    return re.findall(r'@import url\("([^"]+)"\)', _read(STATIC / "css" / "main.css"))


# --------------------------------------------------------------------------------------------- DS 2026 §2

ROW_START = re.compile(r"^\| (\d+) \| `([a-z0-9_/-]+\.css)` \| (≈ )?([0-9.]+) KB \|")


def _table_rows(block: str) -> tuple[list[str], list[tuple[str, list[str]]], list[str]]:
    """Split a block into (lines before the rows, [(file, row lines)], lines after); a row may span lines."""
    lines = block.split("\n")
    head: list[str] = []
    rows: list[tuple[str, list[str]]] = []
    tail: list[str] = []
    i = 0
    while i < len(lines) and not ROW_START.match(lines[i]):
        head.append(lines[i])
        i += 1
    while i < len(lines) and ROW_START.match(lines[i]):
        row = [lines[i]]
        while not row[-1].rstrip().endswith("|") and i + 1 < len(lines):
            i += 1
            row.append(lines[i])
        rows.append((ROW_START.match(row[0]).group(2), row))
        i += 1
    tail = lines[i:]
    return head, rows, tail


def regen_architecture(design: str, result: Result) -> str:
    sheets = cascade()

    def edit(block: str) -> str:
        head, rows, tail = _table_rows(block)
        by_file = dict(rows)
        new_rows: list[list[str]] = []
        for name in sheets:
            if name not in by_file:
                result.manual.append(
                    f"DS 2026 §2: main.css imports `{name}` and the table has no row for it — write its row"
                )
                continue
            lines = list(by_file[name])
            match = ROW_START.match(lines[0])
            weight = _kb((STATIC / "css" / name).stat().st_size)
            number = str(len(new_rows) + 1)
            first = f"| {number} | `{name}` | {match.group(3) or ''}{weight} KB |" + lines[0][match.end() :]
            if match.group(4) != weight:
                result.changes.append(f"DS 2026 §2: {name} {match.group(4)} → {weight} KB")
            if match.group(1) != number:
                result.changes.append(f"DS 2026 §2: {name} renumbered {match.group(1)} → {number}")
            new_rows.append([first, *lines[1:]])
        for name, _lines in rows:
            if name not in sheets:
                result.changes.append(f"DS 2026 §2: row of `{name}` removed (main.css no longer imports it)")
        if [name for name, _ in rows if name in sheets] != [name for name in sheets if name in by_file]:
            result.changes.append("DS 2026 §2: rows put back in main.css's order")
        components = STATIC / "css" / "components.css"
        rebuilt = "\n".join(head + [line for row in new_rows for line in row] + tail)
        if components.exists():
            count = len(re.findall(r"^   (\d+)\. ", _read(components), flags=re.M))
            found = re.search(r"(\d+) sezioni numerate", rebuilt)
            if found and found.group(1) != str(count):
                result.changes.append(f"DS 2026 §2: components.css sections {found.group(1)} → {count}")
                rebuilt = rebuilt[: found.start(1)] + str(count) + rebuilt[found.end(1) :]
        return rebuilt

    return _replace_in(design, "## 2. Architettura CSS", "### 2.1 ", edit)


# --------------------------------------------------------------------------------------------- DS 2026 §6.2

FONT_ROW = re.compile(r"^\| `([a-z0-9-]+\.woff2)` \|(.*)\| ([0-9.]+) \|$", flags=re.M)


def regen_fonts(design: str, result: Result) -> str:
    fonts = {p.name: p.stat().st_size for p in (STATIC / "fonts").glob("*.woff2")}
    total = round(sum(fonts.values()) / 1024)

    def edit(section: str) -> str:
        heading = re.match(r"(.*?)(\d+) file woff2, ≈ (\d+) KB in totale", section)
        if heading is None:
            raise Missing("§6.2 heading: «N file woff2, ≈ N KB in totale»")
        if heading.group(2) != str(len(fonts)) or heading.group(3) != str(total):
            result.changes.append(
                f"DS 2026 §6.2: {heading.group(2)} → {len(fonts)} file woff2, ≈ {heading.group(3)} → {total} KB"
            )
        section = (
            section[: heading.start(2)] + f"{len(fonts)} file woff2, ≈ {total} KB in totale" + section[heading.end() :]
        )
        listed = set()

        def row(match: re.Match) -> str:
            name = match.group(1)
            listed.add(name)
            if name not in fonts:
                result.changes.append(f"DS 2026 §6.2: row of `{name}` removed (the file is gone)")
                return "\x00"
            weight = _kb(fonts[name])
            if match.group(3) != weight:
                result.changes.append(f"DS 2026 §6.2: {name} {match.group(3)} → {weight} KB")
            return f"| `{name}` |{match.group(2)}| {weight} |"

        section = FONT_ROW.sub(row, section).replace("\x00\n", "").replace("\x00", "")
        for name in sorted(set(fonts) - listed):
            result.manual.append(
                f"DS 2026 §6.2: `static/fonts/{name}` has no row — write its family, weight and subset"
            )
        return section

    return _replace_in(design, "### 6.2 ", "### 6.3 ", edit)


# --------------------------------------------------------------------------------------------- DS 2026 §10


def regen_components(design: str, result: Result) -> str:
    files = sorted(p.name for p in COMPONENTS.glob("*.html"))
    catalogue = design[slice(*_span(design, "## 10. Catalogo componenti", "### 10.1 "))]
    sections = re.findall(r"^#### `([a-z_]+\.html)`\s*$", catalogue, flags=re.M)
    for name in sorted(set(files) - set(sections)):
        result.manual.append(f"DS 2026 §10: `templates/components/{name}` has no section — write it")
    for name in sorted(set(sections) - set(files)):
        result.manual.append(
            f"DS 2026 §10: the section of `{name}` describes a file that is gone — remove or retarget it"
        )

    def edit(intro: str) -> str:
        found = re.search(r"^(\d+) file\.", intro, flags=re.M)
        if found is None:
            raise Missing("§10: «N file.»")
        if found.group(1) != str(len(files)):
            result.changes.append(f"DS 2026 §10: {found.group(1)} → {len(files)} file")
        return intro[: found.start(1)] + str(len(files)) + intro[found.end(1) :]

    return _replace_in(design, "## 10. Catalogo componenti", "#### ", edit)


# --------------------------------------------------------------------------------------------- DS 2026 §12


def check_motion(design: str, result: Result) -> None:
    motion = design[slice(*_span(design, "## 12. Motion", "## 13. "))]
    keyframes = sorted(
        {name for sheet in cascade() for name in re.findall(r"@keyframes ([a-z0-9-]+)", _read(STATIC / "css" / sheet))}
    )
    for name in keyframes:
        if f"`{name}`" not in motion:
            result.manual.append(
                f"DS 2026 §12: the keyframe `{name}` is in the cascade and §12 does not name it — describe it"
            )


# --------------------------------------------------------------------------------------------- DS 2026 §13 and §19


def _capture_report() -> dict | None:
    if not CAPTURE_REPORT.exists():
        return None
    return json.loads(_read(CAPTURE_REPORT))


def regen_icons(design: str, result: Result) -> str:
    ids = set(re.findall(r'<symbol id="icon-([a-z0-9-]+)"', _read(STATIC / "img" / "icons.svg")))

    def edit(listing: str) -> str:
        listed = re.findall(r"`([a-z0-9-]+)`", listing)
        for name in sorted(ids - set(listed)):
            result.manual.append(
                f"DS 2026 §13: the sprite's `icon-{name}` is not in the grouped list — place it in a group"
            )
        for name in sorted(set(listed) - ids):
            result.manual.append(f"DS 2026 §13: `{name}` is listed and is not in the sprite — remove it from the list")
        found = re.search(r"(\d+) icone\.", listing)
        if found is None:
            raise Missing("§13: «N icone.»")
        if found.group(1) != str(len(ids)):
            result.changes.append(f"DS 2026 §13: {found.group(1)} → {len(ids)} icone")
        return listing[: found.start(1)] + str(len(ids)) + listing[found.end(1) :]

    design = _replace_in(design, "<!-- icon-list:start -->", "<!-- icon-list:end -->", edit)
    report = _capture_report()
    if report is None:
        result.manual.append("DS 2026 §13/§19: docs/qa/design/capture-report.json is missing — run capture.py")
        return design
    laid_out = sum(data.get("icons", 0) for data in report.values())

    def edit_laid_out(section: str) -> str:
        found = re.search(r"\*\*(\d+) icone disposte\*\*(\s*>?\s*)sulle (\d+) catture", section)
        if found is None:
            raise Missing("§13: «**N icone disposte** … sulle N catture»")
        if found.group(1) != str(laid_out) or found.group(3) != str(len(report)):
            result.changes.append(
                f"DS 2026 §13: {found.group(1)} → {laid_out} icone disposte, {found.group(3)} → {len(report)} catture"
            )
        return (
            section[: found.start()]
            + f"**{laid_out} icone disposte**{found.group(2)}sulle {len(report)} catture"
            + section[found.end() :]
        )

    design = _replace_in(design, "## 13. Iconografia", "## 14. ", edit_laid_out)

    def edit_captures(section: str) -> str:
        found = re.search(r"\*\*(\d+) catture", section)
        if found is None:
            raise Missing("§19: «**N catture»")
        if found.group(1) != str(len(report)):
            result.changes.append(f"DS 2026 §19: {found.group(1)} → {len(report)} catture")
        return section[: found.start(1)] + str(len(report)) + section[found.end(1) :]

    return _replace_in(design, "## 19. Screenshot QA", "## 20. ", edit_captures)


# --------------------------------------------------------------------------------------------- DS 2026 §16


def regen_scripts(design: str, result: Result) -> str:
    scripts = sorted((STATIC / "js").glob("*.js"))
    total = _kb(sum(p.stat().st_size for p in scripts))
    main_js = _read(STATIC / "js" / "main.js")
    functions = set(re.findall(r"^function (init[A-Za-z]+)\(", main_js, flags=re.M))

    def edit(section: str) -> str:
        for path in scripts:
            if f"static/js/{path.name}" not in section:
                result.manual.append(f"DS 2026 §16: `static/js/{path.name}` is not in the table — write its row")
        documented = set(re.findall(r"^\| `(init[A-Za-z]+)` \|", section, flags=re.M))
        for name in sorted(functions - documented):
            result.manual.append(f"DS 2026 §16: main.js's `{name}` has no row — write it")
        for name in sorted(documented - functions):
            result.manual.append(f"DS 2026 §16: `{name}` is documented and main.js no longer has it — remove its row")
        found = re.search(r"≈ ([0-9.]+) KB non compressi in totale", section)
        if found is None:
            raise Missing("§16: «≈ N KB non compressi in totale»")
        if found.group(1) != total:
            result.changes.append(f"DS 2026 §16: static/js {found.group(1)} → {total} KB")
        return section[: found.start(1)] + total + section[found.end(1) :]

    return _replace_in(design, "## 16. Moduli JS", "## 17. ", edit)


# --------------------------------------------------------------------------------------------- ACCESSIBILITY.md


def regen_a11y(a11y: str, design: str, result: Result) -> tuple[str, str]:
    begin, finish = _span(a11y, "<!-- wcag-checklist:start -->", "<!-- wcag-checklist:end -->")
    rows = [
        [cell.strip() for cell in line.strip("|").split("|")]
        for line in a11y[begin:finish].splitlines()
        if re.match(r"^\| \d", line)
    ]
    tally = dict.fromkeys(CHECKLIST_STATUSES, 0)
    for row in rows:
        status = row[3] if len(row) > 3 else ""
        matched = [name for name in CHECKLIST_STATUSES if status.startswith(name)]
        if not matched:
            result.manual.append(f"ACCESSIBILITY.md: criterion {row[0]} has a status no summary counts: {status!r}")
            continue
        tally[matched[0]] += 1
    summary = (
        f"Riepilogo: {len(rows)} criteri — {tally['Conforme']} conformi, {tally['Parziale']} parziali, "
        f"{tally['Da confermare in QA']} da confermare in QA, {tally['Non applicabile']} non applicabili"
    )
    found = re.search(
        r"Riepilogo: \d+ criteri — \d+ conformi, \d+ parziali, \d+ da confermare in QA, \d+ non applicabili", a11y
    )
    if found is None:
        raise Missing("ACCESSIBILITY.md: the «Riepilogo: …» line")
    if found.group(0) != summary:
        result.changes.append(f"ACCESSIBILITY.md: «{found.group(0)}» → «{summary}»")
    a11y = a11y[: found.start()] + summary + a11y[found.end() :]

    gaps_at = a11y.find("## 13. Lacune note")
    if gaps_at < 0:
        raise Missing("ACCESSIBILITY.md: «## 13. Lacune note»")
    ids = re.findall(r"^\| (G-\d\d) \|", a11y[gaps_at:], flags=re.M)
    if ids:
        last = ids[-1]
        for name, text in (("ACCESSIBILITY.md", a11y), ("DS 2026", design)):
            for stale in sorted(set(re.findall(r"G-01 … (G-\d\d)", text)) - {last}):
                result.changes.append(f"{name}: the gap range G-01 … {stale} → G-01 … {last}")
        a11y = re.sub(r"G-01 … G-\d\d", f"G-01 … {last}", a11y)
        design = re.sub(r"G-01 … G-\d\d", f"G-01 … {last}", design)
    return a11y, design


# --------------------------------------------------------------------------------------------- main


def regenerate() -> tuple[dict[Path, tuple[str, str]], Result]:
    """Every document's text before and after, and what changed or needs a writer."""
    result = Result()
    design_before, a11y_before = _read(DESIGN_DOC), _read(A11Y_DOC)
    design = regen_architecture(design_before, result)
    design = regen_fonts(design, result)
    design = regen_components(design, result)
    check_motion(design, result)
    design = regen_icons(design, result)
    design = regen_scripts(design, result)
    a11y, design = regen_a11y(a11y_before, design, result)
    return {DESIGN_DOC: (design_before, design), A11Y_DOC: (a11y_before, a11y)}, result


def main(argv: list[str] | None = None) -> int:
    parser = argparse.ArgumentParser(description="Regenerate the DS 2026 inventory tables and the A11Y counts.")
    parser.add_argument("--write", action="store_true", help="rewrite the stale figures (default: check only)")
    args = parser.parse_args(argv)
    for stream in (sys.stdout, sys.stderr):
        if hasattr(stream, "reconfigure"):
            stream.reconfigure(errors="replace")
    try:
        documents, result = regenerate()
    except Missing as exc:
        print(f"regen_design_inventory: a section this script reads is gone: {exc}", file=sys.stderr)
        return 2
    stale = [path for path, (before, after) in documents.items() if before != after]
    for line in result.changes:
        print(("rewrote: " if args.write else "stale:   ") + line)
    if args.write:
        for path in stale:
            text = documents[path][1]
            assert "\r" not in text
            path.write_bytes(text.encode("utf-8"))
    for line in result.manual:
        print("needs a writer: " + line)
    if not result.changes and not result.manual:
        print("regen_design_inventory: the inventory tables and the counts are current")
    elif not args.write and stale:
        print(f"regen_design_inventory: {len(result.changes)} stale figure(s); run with --write")
    if result.manual:
        return 2
    return 1 if stale and not args.write else 0


if __name__ == "__main__":
    raise SystemExit(main())
